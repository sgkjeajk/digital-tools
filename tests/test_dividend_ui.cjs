const element=id=>{if(!elements.has(id))elements.set(id,{textContent:''});return elements.get(id);};
const context=vm.createContext({window:{},TextEncoder,Uint8Array,Uint32Array,DataView,Blob,Date,Intl,Map,console});
vm.runInContext(fs.readFileSync('stock-monitor/xlsx-writer.js','utf8'),context);
context.XlsxWriter=context.window.XlsxWriter;
context.$=element;
context.valid=n=>typeof n==='number'&&Number.isFinite(n);
context.sg=x=>x||'';
context.excelDate=()=> 'test';
context.exportRows=[{ticker:'TEST',type:'Stock',name:'Test',region:'US',currency:'USD',prev_close:100,current_price:110,ath:120,dividend_per_share:2,dividend_yield_pct:2,dividend_declaration_date:'01 Jan 2026',ex_dividend_date:'02 Jan 2026',dividend_payment_date:'03 Jan 2026'}];
let exported;
context.download=(name,blob)=>{exported=blob;};
context.showExportPanel=()=>{};
const monitor=fs.readFileSync('stock-monitor/monitor.js','utf8');
vm.runInContext(monitor.slice(monitor.indexOf('function exportExcel(){'),monitor.indexOf('function render(',monitor.indexOf('function exportExcel(){'))),context);
context.exportExcel();
assert(exported instanceof Blob);
const admin=fs.readFileSync('stock-monitor/admin.js','utf8');
context.ECGitHub={getCheckerSnapshot:async path=>path==='market-data.json'?{last_check_status:'prices_refreshed',last_check_completed_at:'2026-10-14T22:00:00Z'}:{generated_at:'2026-10-14T22:01:00Z',instruments:[{dividend_error:'Unavailable'}]}};
